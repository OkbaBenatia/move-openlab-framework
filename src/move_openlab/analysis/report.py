"""Exportable reports: a self-describing Markdown summary and a CSV table of a method comparison, plus the full JSON
record. Reports cite campaign ids and checksums so that every number can be traced back to a locked record."""
from __future__ import annotations

import csv
import io

from ..version import APP_NAME, app_version
from .compare import compare


def _fmt(v) -> str:
    if v is None:
        return "—"
    if isinstance(v, float):
        return f"{v:.4g}"
    return str(v)


def comparison_csv(ws, cid: str) -> str:
    d = compare(ws, cid)
    metric_ids = [m["id"] for m in d["metrics"]]
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(["method_id", "version", "source", "code_sha256", "campaign_id", "campaign_kind", "researcher",
                "installation_id", "scenarios", "all_feasible", *[f"total_{m}" for m in metric_ids], "equals_reference_optimum",
                "shortfall", "final_level_gap_pct_mean", "final_level_gap_pct_max", "mean_rank",
                "median_solver_time_s", "median_total_time_s", "repetitions_consistent", "reproduction_status",
                "optimality_scope"])
    for r in d["rows"]:
        gap = r.get("final_level_gap_pct") or {}
        w.writerow([r["method_id"], r["version"], r["source"], r["code_sha256"] or "", r["campaign_id"], r["campaign_kind"],
                    r["researcher"], r["installation_id"], r["scenarios"], r["all_feasible"],
                    *[r["totals"].get(m) for m in metric_ids], r.get("optimal"), r.get("shortfall"), gap.get("mean"),
                    gap.get("max"), r["mean_rank"], r["median_solver_time_s"], r["median_total_time_s"],
                    r["repetitions_consistent"], r["reproduction_status"] or "",
                    "; ".join(f"{n} x {k}" for k, n in (r.get("optimality_scope") or {}).items())])
    return buf.getvalue()


def comparison_markdown(ws, cid: str) -> str:
    d = compare(ws, cid)
    metric_ids = [m["id"] for m in d["metrics"]]
    lines = [f"# Method comparison — {d['problem']['title']}", "",
             f"Generated by {APP_NAME} {app_version()} from locked campaign records.", "",
             "## Provenance", "", "| Campaign | Kind | Researcher | Installation | Checksum |", "|---|---|---|---|---|"]
    for l in d["lineage"]:
        lines.append(f"| `{l['campaign_id']}` | {l['kind']} | {l['owner_display']} | `{l['installation_id']}` | "
                     f"`{(l['checksum'] or 'not locked')[:16]}` |")
    lines += ["", "## Problem", "", f"- Problem: `{d['problem']['problem_id']}` "
              f"(specification {d['problem']['problem_spec_version']}, instance schema `{d['problem']['instance_schema']}`)",
              f"- Objective: `{d['problem']['objective_spec_id']}` — {d['ranking_rule']}",
              f"- Scenarios: {d['scenarios']} (identical instance hashes across campaigns: "
              f"{'yes' if d['instance_hashes_identical'] else 'no'})",
              f"- Synthetic data: {'yes' if d['synthetic'] else 'no'}"]
    if d["reference"]:
        lines.append(f"- Reference: `{d['reference']['method_id']}` in campaign `{d['reference']['campaign_id']}` "
                     f"({d['reference']['owner_display']})")
    lines += ["", "## Results", "",
              "| Method | Origin | Researcher | Valid | " + " | ".join(f"Total {m}" for m in metric_ids)
              + " | Equals reference optimum | Shortfall | Gap % mean / max | Mean rank | What it proves"
              " | Median solver · total time (s) | Status |",
              "|" + "---|" * (12 + len(metric_ids))]
    for r in d["rows"]:
        gap = r.get("final_level_gap_pct") or {}
        lines.append(f"| `{r['method_id']}@{r['version']}` | {r['origin']} | {r['researcher']} | "
                     f"{'yes' if r['all_feasible'] else 'NO'} | " + " | ".join(_fmt(r["totals"].get(m)) for m in metric_ids)
                     + f" | {_fmt(r.get('optimal'))}/{r['scenarios']} | {_fmt(r.get('shortfall'))} | "
                     f"{_fmt(gap.get('mean'))} / {_fmt(gap.get('max'))} | {_fmt(r['mean_rank'])} | "
                     + ("; ".join(f"{n} × {k}" for k, n in (r.get("optimality_scope") or {}).items()) or "—") + " | "
                     f"{_fmt(r['median_solver_time_s'])} · {_fmt(r['median_total_time_s'])} | "
                     f"{r['reproduction_status'] or r['origin']} |")
    if d["warnings"]:
        lines += ["", "## Warnings", ""] + [f"- {w}" for w in d["warnings"]]
    lines += ["", "## Definitions", "",
              f"- Solver time: {d['timing_definitions']['solver_time']}.",
              f"- Total time: {d['timing_definitions']['total_time']}.",
              "- Equals reference optimum: every objective level equals the reference method's value on the scenario "
              "(a heuristic can reach it without proving it).",
              "- What it proves: the optimality scope of each run (proven optimal for the full problem, optimal for "
              "a reduced instance only, not proven, heuristic or invalid).",
              "- Gap: relative difference on the last objective level, only where all previous levels equal the "
              "reference (positive = worse).", ""]
    return "\n".join(lines)
