#!/usr/bin/env python3
"""Build the public sample trip dataset (scenario import example): a small, fully synthetic CSV of commuting trips
inside the box of the Montbéliard demonstration. Deterministic (fixed seed): running it again writes the same bytes.

The trips are generated, not observed: origins and destinations are drawn around the centres of twelve communes of the
area (public geographic facts) with a random offset; three quarters follow seven commuting corridors around three
departure waves of the morning peak, so that sampled drivers and riders can share rides. No personal or observed
mobility data is involved. The file is dedicated to the public domain (CC0 1.0).

    python scripts/build_sample_trips.py          # writes examples/scenario-import/ and the packaged copy
"""
from __future__ import annotations

import hashlib
import json
import random
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NAME = "montbeliard-synthetic-trips.csv"
SEED, ROWS, DATE = 20261115, 120, "2026-10-06"
BOX = (47.42, 6.66, 47.60, 6.96)                    # south, west, north, east: the demonstration's road-network box
CENTRES = [("Montbéliard", 47.510, 6.798, 5), ("Audincourt", 47.483, 6.840, 3), ("Sochaux", 47.515, 6.829, 3),
           ("Valentigney", 47.463, 6.833, 2), ("Bethoncourt", 47.535, 6.805, 2), ("Seloncourt", 47.459, 6.857, 1),
           ("Exincourt", 47.494, 6.833, 1), ("Étupes", 47.507, 6.863, 1), ("Grand-Charmont", 47.527, 6.826, 1),
           ("Bavans", 47.483, 6.732, 1), ("Voujeaucourt", 47.475, 6.775, 1), ("Héricourt", 47.578, 6.762, 2)]


# Commuting corridors (origin commune -> destination commune): most trips follow one of them, within a few minutes of a
# departure wave, so that drivers and riders of a sampled scenario can actually share rides.
CORRIDORS = [("Héricourt", "Montbéliard"), ("Bethoncourt", "Sochaux"), ("Valentigney", "Montbéliard"),
             ("Seloncourt", "Audincourt"), ("Bavans", "Montbéliard"), ("Audincourt", "Sochaux"), ("Voujeaucourt", "Audincourt")]
WAVES = [7 * 3600, 7 * 3600 + 1800, 8 * 3600]            # 07:00, 07:30, 08:00


def build() -> bytes:
    rng = random.Random(SEED)
    centre = {c[0]: c for c in CENTRES}
    weights = [c[3] for c in CENTRES]

    def point(c, spread=1.0):
        while True:
            la, lo = c[1] + rng.gauss(0, 0.0035 * spread), c[2] + rng.gauss(0, 0.005 * spread)
            if BOX[0] + 0.005 < la < BOX[2] - 0.005 and BOX[1] + 0.005 < lo < BOX[3] - 0.005:
                return round(la, 5), round(lo, 5)
    lines = ["date,departure_time,origin_lat,origin_lon,destination_lat,destination_lon,role"]
    for _ in range(ROWS):
        if rng.random() < 0.75:                          # a corridor trip around a departure wave
            a, b = (centre[x] for x in rng.choice(CORRIDORS))
            (ola, olo), (dla, dlo) = point(a, 0.6), point(b, 0.6)
            t = (rng.choice(WAVES) + int(rng.gauss(0, 360))) // 300 * 300
        else:                                            # a trip between two other communes, any time of the peak
            a = rng.choices(CENTRES, weights)[0]
            b = rng.choices([c for c in CENTRES if c is not a], [c[3] for c in CENTRES if c is not a])[0]
            (ola, olo), (dla, dlo) = point(a), point(b)
            t = int(rng.triangular(6 * 3600 + 1800, 9 * 3600 + 1800, 7 * 3600 + 2700)) // 300 * 300
        t = max(6 * 3600, min(9 * 3600 + 1800, t))
        role = "driver" if rng.random() < 0.4 else "rider"
        lines.append(f"{DATE},{t // 3600:02d}:{t % 3600 // 60:02d},{ola:.5f},{olo:.5f},{dla:.5f},{dlo:.5f},{role}")
    return ("\n".join(lines) + "\n").encode("utf-8")


def main() -> None:
    raw = build()
    info = dict(filename=NAME, title="Montbéliard synthetic commuting trips (sample dataset)", rows=ROWS, bytes=len(raw),
                sha256=hashlib.sha256(raw).hexdigest(), format="CSV, UTF-8, comma-separated, one trip per row",
                columns=["date", "departure_time", "origin_lat", "origin_lon", "destination_lat", "destination_lon", "role"],
                mapping=dict(origin_lat="origin_lat", origin_lon="origin_lon", destination_lat="destination_lat",
                             destination_lon="destination_lon", departure="departure_time", date="date", role="role"),
                bbox=list(BOX), synthetic=True, generator=dict(script="scripts/build_sample_trips.py", seed=SEED),
                licence=dict(id="CC0-1.0", name="Creative Commons Zero 1.0 (public domain dedication)",
                             url="https://creativecommons.org/publicdomain/zero/1.0/"),
                source="generated by this project: synthetic commuting trips around commune centres of the Montbéliard area; "
                       "no observed or personal mobility data")
    for d in (ROOT / "examples" / "scenario-import", ROOT / "src" / "move_openlab" / "samples" / "trips"):
        d.mkdir(parents=True, exist_ok=True)
        (d / NAME).write_bytes(raw)
    (ROOT / "src" / "move_openlab" / "samples" / "trips" / "trips.json").write_text(json.dumps(info, indent=1, ensure_ascii=False) + "\n")
    (ROOT / "examples" / "scenario-import" / "SHA256SUMS").write_text(f"{info['sha256']}  {NAME}\n")
    print(NAME, info["bytes"], "bytes", info["sha256"])


if __name__ == "__main__":
    main()
